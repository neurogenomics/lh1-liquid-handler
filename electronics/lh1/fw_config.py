"""Resolve the LH-1 Klipper configuration the way Klipper reads it: printer.cfg (shared core) with its [include ...] read in
place and a section named twice merged (Klipper's configfile uses a non-strict parser: options of a later section of the
same name are added to / replace the earlier ones).  The core includes exactly one size file, lh1_size_<S|M|L>.cfg.

resolve(size=None) -> (text, info).  size=None uses the include line in printer.cfg; size='M' substitutes lh1_size_M.cfg
for it (what an upgrade does).  write(size) writes electronics/lh1/out/firmware_resolved_<size>.cfg, the file the guard
cases (fw_render_check.py) and check.py read.  The resolved file is GENERATED: never edit it, never load it on the machine
(Klipper loads printer.cfg and follows the include itself).
"""
import configparser
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
FW = ROOT / "firmware" / "lh1"
SIZES = ("S", "M", "L")
SIZE_FILE = "lh1_size_{}.cfg"
# the only sections a size file may hold (everything else is shared core)
SIZE_SECTIONS = re.compile(r"^(stepper_y|gcode_macro _LH_SIZE|gcode_button safe_[a-z]\d_[ab]|gcode_button shutter_h[12])$")
INCLUDE = re.compile(r"(?m)^\[include ([^\]]+)\]\s*$")


def _parser(strict):
    return configparser.RawConfigParser(strict=strict, delimiters=(":",), comment_prefixes=("#", ";"),
                                        inline_comment_prefixes=("#",))


def core_text():
    return (FW / "printer.cfg").read_text()


def included_size(text=None):
    """the size named by the core's include line(s): returns (size or None, [include names])"""
    inc = INCLUDE.findall(text if text is not None else core_text())
    m = [re.fullmatch(r"lh1_size_([SML])\.cfg", i.strip()) for i in inc]
    sizes = [x.group(1) for x in m if x]
    return (sizes[0] if len(sizes) == 1 and len(inc) == 1 else None), inc


def resolve(size=None):
    core = core_text()
    built, inc = included_size(core)
    size = size or built
    if size not in SIZES:
        raise ValueError(f"printer.cfg must include exactly one lh1_size_<S|M|L>.cfg (found {inc})")
    size_txt = (FW / SIZE_FILE.format(size)).read_text()
    # Klipper: the include is read where it stands; here it is the last line, so core then size file
    text = INCLUDE.sub("", core) + "\n" + size_txt
    cp = _parser(strict=False)
    cp.read_string(text)
    lines = [f"# GENERATED by electronics/lh1/fw_config.py from firmware/lh1/printer.cfg + {SIZE_FILE.format(size)}: "
             "what Klipper reads after following the include.  Do not edit, do not load.", ""]
    for sec in cp.sections():
        lines.append(f"[{sec}]")
        for k, v in cp.items(sec):
            vv = v.split("\n")
            lines.append(f"{k}: {vv[0]}".rstrip())
            lines += [("    " + x) if x.strip() else "" for x in vv[1:]]
        lines.append("")
    sp = _parser(strict=True)
    sp.read_string(size_txt)
    info = {"size": size, "built_size": built, "includes": inc, "size_sections": sp.sections(),
            "bad_size_sections": [s for s in sp.sections() if not SIZE_SECTIONS.match(s)]}
    return "\n".join(lines) + "\n", info


def out_path(size):
    return HERE / "out" / f"firmware_resolved_{size}.cfg"


def write(size=None):
    text, info = resolve(size)
    p = out_path(info["size"])
    p.parent.mkdir(exist_ok=True)
    p.write_text(text)
    return p, info


# ---------------- reduced build profiles (MVP, 24 Nov 2026) ----------------
# Klipper cannot delete a section through an include, so a reduced build loads its own top file, GENERATED from the core:
# firmware/lh1/printer_<name>.cfg = printer.cfg without the hardware sections of the absent device groups (profile yaml
# firmware_sections), then [include lh1_size_<base>.cfg] and [include lh1_profile_<name>.cfg] (the profile: _LH_PROFILE
# values, the phantom printer Z, DEVICE_ABSENT refusals).  Every macro of the core stays; nothing is edited by hand.
def profile_yaml(name):
    import yaml
    return yaml.safe_load((HERE / f"profile_{name}.yaml").read_text())


def dropped_sections(prof):
    groups = list(prof["absent_groups"])
    pats = [p for g in groups for p in prof["firmware_sections"].get(g, [])]
    if prof.get("guard") == "open_frame":
        pats.append("gcode_button door")
    return [re.compile(f"^{p}$") for p in pats]


def profile_core_text(name):
    """text of the loadable firmware/lh1/printer_<name>.cfg: the core with the absent groups' sections cut out (section
    header to the next header, comments in between go with it), the size include replaced by size + profile includes"""
    prof = profile_yaml(name)
    pats = dropped_sections(prof)
    out, skip, cut = [], False, []
    for ln in core_text().splitlines():
        m = re.match(r"^\[([^\]]+)\]\s*$", ln)
        if m:
            skip = any(p.match(m.group(1)) for p in pats)
            if skip:
                cut.append(m.group(1))
        if not skip:
            out.append(ln)
    txt = "\n".join(out) + "\n"
    txt = INCLUDE.sub(f"[include {SIZE_FILE.format(prof['base_size'])}]\n[include lh1_profile_{name}.cfg]", txt)
    head = (f"# GENERATED by electronics/lh1/gen_size_files.py --profile {name} from firmware/lh1/printer.cfg: do not edit.  Klipper loads THIS\n"
            f"# file for the {name} build: the shared core without the hardware sections of the absent device groups ({', '.join(prof['absent_groups'])}),\n"
            f"# {len(cut)} sections cut: {', '.join(cut)}.  Every macro of the core is kept; lh1_profile_{name}.cfg makes absent devices refuse.\n")
    return head + txt, cut


def resolve_profile(name):
    prof = profile_yaml(name)
    core, cut = profile_core_text(name)
    size_txt = (FW / SIZE_FILE.format(prof["base_size"])).read_text()
    prof_txt = (FW / f"lh1_profile_{name}.cfg").read_text()
    text = re.sub(r"(?m)^\[include [^\]]+\]\s*$", "", core) + "\n" + size_txt + "\n" + prof_txt
    cp = _parser(strict=False)
    cp.read_string(text)
    lines = [f"# GENERATED by electronics/lh1/fw_config.py from firmware/lh1/printer_{name}.cfg + {SIZE_FILE.format(prof['base_size'])} + "
             f"lh1_profile_{name}.cfg: what Klipper reads for the {name} build.  Do not edit, do not load.", ""]
    for sec in cp.sections():
        lines.append(f"[{sec}]")
        for k, v in cp.items(sec):
            vv = v.split("\n")
            lines.append(f"{k}: {vv[0]}".rstrip())
            lines += [("    " + x) if x.strip() else "" for x in vv[1:]]
        lines.append("")
    return "\n".join(lines) + "\n", {"profile": name, "cut": cut}


def write_profile(name):
    text, info = resolve_profile(name)
    p = HERE / "out" / f"firmware_resolved_{name}.cfg"
    p.write_text(text)
    return p, info


if __name__ == "__main__":
    for s_ in SIZES:
        print(write(s_))
    if (FW / "lh1_profile_MVP.cfg").exists():
        print(write_profile("MVP")[0])
