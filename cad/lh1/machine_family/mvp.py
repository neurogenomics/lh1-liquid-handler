def mcl_parts(x, s, unlocked=False):
    zt = HL.z_top(s)
    xs = x + HL.STUD["x"]
    dy = -MCL["travel"] if unlocked else 0.0
    z0, z1 = zt + MCL["z0"], zt + MCL["z1"]
    wide = B(xs - MCL["w"] / 2, xs + MCL["w"] / 2, MCL["y_wide_front"] + dy, MCL["y_tips"] + dy, z0, z1)
    tongue = B(xs - MCL["tongue_w"] / 2, xs + MCL["tongue_w"] / 2, MCL["tab"][1] + dy - 0.01, MCL["y_wide_front"] + dy + 0.01, z0, z1)
    tab = B(xs - MCL["tab_w"] / 2, xs + MCL["tab_w"] / 2, MCL["tab"][0] + dy, MCL["tab"][1] + dy, z0, z1)
    heel = B(xs - MCL["w"] / 2, xs + MCL["w"] / 2, MCL["heel"][0] + dy, MCL["heel"][1] + dy, zt + 8.0, z0 + 0.01)
    se = MCL["slot_end_c"] + dy
    slot = [B(xs - MCL["slot_w"] / 2, xs + MCL["slot_w"] / 2, se, MCL["y_tips"] + dy + 1, zt + 7.0, z1 + 1), cyl(xs, se, zt + 7.0, z1 + 1, MCL["slot_w"]),
            cyl(xs, MCL["screw_y"] + dy, z0 - 1, z1 + 1, MCL["screw_d"])]
    plate = cut_all(fuse_all([wide, tongue, tab, heel]), slot)
    screw = cyl(xs, MCL["screw_y"] + dy, zt + 8.0 + (1.6 if unlocked else 0.0), z1 - 0.5, MCL["screw_d"] - 0.1)
    return {"mcl_plate": plate, "mcl_screw": screw}


class MVPHead(G.FamilyHead):
    """FamilyHead (same parts, same positions) reduced to carriage A with the manual clamp; same parts() interface"""

    def __init__(self):
        super().__init__()
        self.mcl = {f"{AXIS}:{k}": v for k, v in mcl_parts(P.L_AXIS_X[AXIS], 0.0).items()}
        for v in self.mcl.values():
            self.bb[id(v)] = v.BoundingBox()

    def parts(self, xc, yf, sA=0.0, sB=0.0, sG=0.0, toolA=TOOL, toolB=None, tipsA=True, tipsB=False):
        out = [(k, v, (xc, yf, ZB)) for k, v in self.fixed.items() if k.startswith(FIXED_KEEP)]
        off = (xc, yf, ZB - sA)
        out += [(k, v, off) for k, v in self.axes[AXIS].items() if k.split(":")[-1] not in DROP_A]
        out += [(k, v, off) for k, v in self.mcl.items()]
        if toolA:
            out += [(k, v, off) for k, v in self.tools[(AXIS, toolA)].items()]
            if tipsA and (AXIS, toolA) in self.tips:
                out.append((f"{AXIS}:tool:tips", self.tips[(AXIS, toolA)], off))
        out.append((f"{AXIS}:ffc_loop", self.loop(AXIS, sA), (xc, yf, ZB)))
        return out


def head_internal(head):
    designed = {("mcl_plate", "bracket"), ("mcl_screw", "bracket"), ("mcl_screw", "mcl_plate"), ("mcl_plate", "stud"),
                ("eject_pin", "bracket"), ("pusher_collar", "bracket"), ("pusher_rod", "bracket")}
    hits, n = [], 0
    for s in (0.0, 120.0, P.L_Z_TRAVEL, -P.Z_EJECT_TRAVEL):
        pp = head.parts(0.0, 0.0, sA=s, tipsA=False)
        sols = [(k, v.translate(V(*off))) for k, v, off in pp]
        n += 1
        for i, (ka, a) in enumerate(sols):
            la = ka.split(":")[-1]
            for kb, b in sols[i + 1:]:
                lb = kb.split(":")[-1]
                if not ({la, lb} & {"mcl_plate", "mcl_screw"}):
                    continue
                if (la, lb) in designed or (lb, la) in designed:
                    continue
                ba, bb = a.BoundingBox(), b.BoundingBox()
                if ba.xmax < bb.xmin or bb.xmax < ba.xmin or ba.ymax < bb.ymin or bb.ymax < ba.ymin or ba.zmax < bb.zmin or bb.zmax < ba.zmin:
                    continue
                v = M.overlap_volume(a, b)
                if v > 1.0 or v < 0:
                    hits.append({"s": s, "a": ka, "b": kb, "mm3": round(v, 1)})
    # designed contacts: report their overlap volumes (must be ~0: touching faces)
    pp = head.parts(0.0, 0.0, sA=0.0, tipsA=False)
    d = {k.split(":")[-1]: v.translate(V(*off)) for k, v, off in pp}
    contacts = {f"{a}/{b}": round(M.overlap_volume(d[a], d[b]), 2) for a, b in (("mcl_plate", "bracket"), ("mcl_plate", "stud"), ("mcl_screw", "bracket"))}
    # unlocked (fork pulled forward to its stop): the prongs must clear the stud head (the tool drops out)
    unl = mcl_parts(0.0, 0.0, unlocked=True)["mcl_plate"]
    stud = HL.tool_module(0.0, 0.0, TOOL)["stud"]
    return {"poses": n, "hits": hits, "designed_contact_overlap_mm3": contacts,
            "unlocked_plate_vs_stud_mm3 (0 = the tool drops out)": round(M.overlap_volume(unl, stud), 2),
            "method": "MCL-1 plate and screw against every other MVP head part at s 0, 120, full stroke and eject over-travel, OCC boolean > 1 mm3"}


