def run_checks(S, items, head, pl):
    sc = M.Scene(items)
    res = {"transit": [], "lowered": [], "eject": [], "reach_fail": [], "reach_limit_body_in_labware": [], "configs": 0}
    bpt = {}
    ax_x = P.L_AXIS_X[AXIS]

    def run(hp, label, skip=lambda hn, it: False):
        res["configs"] += 1
        return M.check_config(sc, head, hp, label, skip)
    for n, p in pl.items():
        x, y = p["c"]
        xc, yf = min(max(x - ax_x, S.XC0), S.XC1), min(max(y - AY, S.YF0), S.YF1)
        for tips in (True, False):
            res["transit"] += run(head.parts(xc, yf, tipsA=tips), f"transit over {n} (tips {'on' if tips else 'off'})")
    for xc in (S.XC0, S.XC1):
        for yf in (S.YF0, S.YF1):
            res["transit"] += run(head.parts(xc, yf), f"travel corner xc {xc:g} yf {yf:g}")
    for n, key, pts, s_t, tips, what, excl in CK.pipette_targets(S, pl):
        if key != TOOL:
            continue
        ok_all, worst, lim_fr = True, [], set()
        for (x, y) in pts:
            xc, yf = x - ax_x, y - AY
            if not CK.in_travel(S, xc, yf):
                res["reach_fail"].append({"place": n, "point": [x, y], "xc": round(xc, 1), "yf": round(yf, 1)})
                ok_all = False
                continue
            if s_t > P.L_Z_TRAVEL + 1e-6:
                res["reach_fail"].append({"place": n, "depth_short_mm": round(s_t - P.L_Z_TRAVEL, 1)})
                ok_all = False
            for frac in (0.5, 0.85, 1.0):
                s = min(s_t, P.L_Z_TRAVEL) * frac

                def skip(hn, it, n=n, excl=excl):
                    return (it.get("place") == n and (it["cls"] == "labware" or it.get("tool_contact")) and hn.startswith(AXIS + ":tool:")
                            and hn.split(":")[-1] in excl)
                h = run(head.parts(xc, yf, sA=s, tipsA=tips), f"{TOOL} lowered at {n} ({what}) s {s:.0f} at ({x:.0f}, {y:.0f})", skip)
                lim = [q for q in h if q["place"] == n and q["cls"] == "labware" and q["head_part"].startswith(AXIS + ":tool:")]
                h = [q for q in h if q not in lim]
                res["reach_limit_body_in_labware"] += lim
                res["lowered"] += h
                worst += h
                if lim:
                    lim_fr.add(frac)
        k = f"{TOOL}@{AXIS}: {what}"
        bpt.setdefault(n, {})[k] = {"reached": ok_all and not lim_fr, "interferences": len(worst), "s_target": round(s_t, 1),
                                    "reach_limit": f"tool body meets the labware at {min(lim_fr) * 100:.0f} % of the stroke" if lim_fr else None}
    tw = [n for n, p in pl.items() if p["key"] == "TIPWASTE"][0]
    cx, cy = pl[tw]["c"]
    res["eject"] += run(head.parts(cx - ax_x, cy - AY, sA=-P.Z_EJECT_TRAVEL), f"eject over-travel {TOOL} at {tw}")
    bpt[tw][f"{TOOL}@{AXIS}: eject over-travel against the fixed finger"] = {"reached": True, "interferences": len(res["eject"]),
                                                                              "s_target": -P.Z_EJECT_TRAVEL}
    return res, bpt


def deck_positions(S, pl, bpt):
    ax_x = P.L_AXIS_X[AXIS]
    out = {}
    for n, p in pl.items():
        cx, cy = p["c"]
        pts = [(cx - 49.5, cy), (cx + 49.5, cy)]
        intr = all(CK.in_travel(S, x - ax_x, y - AY) for x, y in pts)
        d = {"station": p["key"] if not (n == "F4") else "EMPTY (MVP shaker-window blank IN-B)", "centre_xy": list(p["c"]), "height_above_seat_mm": p["h"],
             "role": ROLE.get(n, "blanked: plain insert IN-P (the starter's standard insert)" if n != "F4" else
                     "blanked: IN-B shaker-window blank (MVP only; the shaker tray takes the window at stage 3)"),
             "eight_channel_columns_1_and_12_in_XY_travel (carriage A)": intr}
        if n in bpt:
            d["checks (zero interference = reached clean)"] = bpt[n]
        out[n] = d
    return out


def z_clear(head, items):
    hp = head.parts(0.0, 0.0)
    low_f, who_f = M.lowest_point(head, hp, "fixed")
    low_t, who_t = M.lowest_point(head, hp)
    deck = [it for it in items if it["group"] == "station" and it["solid"].BoundingBox().zmax > 0]
    tall = max(deck, key=lambda it: it["solid"].BoundingBox().zmax)
    zt = tall["solid"].BoundingBox().zmax
    return {"head_lowest_fixed_z": round(low_f, 1), "lowest_fixed_part": who_f, "lowest_with_tips_at_s0_z": round(low_t, 1), "lowest_part": who_t,
            "tallest_deck_item": tall["name"], "tallest_deck_item_z": round(zt, 1), "fixed_head_clearance_mm": round(low_f - zt, 1),
            "tips_clearance_at_s0_mm": round(low_t - zt, 1)}


