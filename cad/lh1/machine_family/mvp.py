    s = B(b["x0"], b["x1"], b["y0"], b["y1"], 0.0, b["t"])
    holes = [cyl(cx + x, cy + y, -1, b["t"] + 1, 4.5) for x, y in P.INSERT_SCREWS] + [cyl(cx + x, cy + y, -1, b["t"] + 1, 4.0) for x, y in P.INSERT_DOWELS]
