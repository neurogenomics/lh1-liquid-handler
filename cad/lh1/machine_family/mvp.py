def scene_mvp():
    """items of the MVP: frame, deck strips, drawer, enclosure and services from the FULL starter (unchanged parts), stations from the
    MVP layout.  Returns items, the MVP place dict, the full S place dict and the two Size objects."""
    S, Sm = mvp_size()
    pl_full = SC.places(S)
    st_full, _ = SC.station_items(S, pl_full)
    dr_full = SC.drawer_items(S, pl_full)
    under_full = [i for i in st_full + dr_full if i["group"] == "station"]
    frame = SC.frame_items(S, under_full, pl_full)                      # deck bars and posts exactly as the starter's
    deck = [it for it in SC.deck_items(S, pl_full) if not it["name"].startswith("CON-F") or it["name"].startswith("CON-F_B1_")]
    pl = SC.places(Sm)
    st, _ = SC.station_items(Sm, pl)
    st = [it for it in st if it["name"] not in NO_VC2_CAMERA and it["name"] != "F4_IN-P_plain_insert"]
    st.append(dict(name="F4_IN-B_shaker_window_blank (MVP only)", solid=f4_blank(pl), group="station", cls="part", place="F4",
                   part="IN-B_shaker_window_blank", mat="al", key="EMPTY"))
    dr = [it for it in dr_full if it["name"].startswith(DRAWER_KEEP)]
    enc = [it for it in SC.enclosure_items(S, SC.floor_holes(S, pl_full)) if not it["name"].startswith(ENCL_DROP)]
    srv = SC.services_items(S, pl_full)
    items = frame + deck + st + dr + enc + srv
    return items, pl, pl_full, S, Sm


