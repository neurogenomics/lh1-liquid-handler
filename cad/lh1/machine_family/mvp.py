def machine_rows(BF, items, gm):
    rows = BF.parts_rows(items + gm)
    s_rows = list(csv.DictReader(open(HERE / "out" / "S" / "parts_S.csv")))
    s_keys = {(r["part"], r["envelope_mm"]): int(r["qty"]) for r in s_rows}
    s_names = {}
    for r in s_rows:
        s_names[r["part"]] = s_names.get(r["part"], 0) + int(r["qty"])
    out = []
    for r in rows:
        k = (r["part"], r["envelope_mm"])
        if r["part"].startswith("IN-B_shaker_window_blank"):
            inf, note = "no (MVP only)", ("closes the starter's shaker window at F4, which is wider than a plain insert; laser-cut 5 mm Al, ~£10 class; "
                                          "kept afterwards as the service cover when the shaker is out (stage 3 fits the shaker tray)")
        elif k in s_keys:
            sq = s_keys[k]
            inf = "yes" if r["qty"] <= sq else f"yes ({sq} used in the starter; {r['qty'] - sq} spare)"
            note = ""
            if r["part"] == "IN-P_plain_insert_plate":
                note = ("blanks every starter window the MVP does not use; the starter uses %d, the rest become blanks for a module taken out for "
                        "service or go into the added rows of M and L" % sq)
        elif r["part"] in s_names:
            inf, note = "yes (same part; envelope differs in the model)", ""
        else:
            inf, note = "CHECK", "not matched in parts_S.csv"
        out.append({"name": r["part"], "quantity": int(r["qty"]), "make_or_buy": "buy" if r["kind"] == "bought" else "make", "material": r["material"],
                    "process": r["process"], "sub_assembly": r["group"], "in_full_starter": inf, "envelope_mm": r["envelope_mm"],
                    "mass_kg_each": r["mass_kg_each"], "note": note})
    lab = {}
    for it in items:
        if it["group"] == "station" and it["cls"] == "labware":
            k = it.get("part") or it["name"]
            lab[k] = lab.get(k, 0) + 1
    for k, q in lab.items():
        out.append({"name": k, "quantity": q, "make_or_buy": "buy (labware / consumable)", "material": "pp / as bought", "process": "bought",
                    "sub_assembly": "deck labware", "in_full_starter": "yes (labware, not in parts_S.csv)", "envelope_mm": "", "mass_kg_each": "",
                    "note": "placed by the person; the P300 frame takes one 96-tip p300 refill wafer by hand" if "p300" in k else ""})
    for name, kind, mat, proc, sub, st in HEAD_ROWS:
        q0 = st.get(0, 0)
