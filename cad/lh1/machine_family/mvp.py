def clamp_calcs():
    ys = HL.AXY[1]
    heel = sum(MCL["heel"]) / 2
    a = ys - heel if ys > heel else heel - ys
    a = abs(heel - ys)
    b = abs(heel - MCL["screw_y"])
    ratio = b / a
    d = MCL["screw_d"] / 1000.0
    f_screw = [MCL["torque_Nm"] / (k * d) for k in (MCL["K"][1], MCL["K"][0])]
    pre = [round(f * ratio) for f in f_screw]
    R = HL.C["R"] / 1000.0
    ej_arm = abs(G.EJECT_DX_NEW) + 4.0
    cases = {"tip pick-up, eight tips, %g N design load half on an end tip 31.5 mm off" % P.DESIGN_LOAD_N: (0.0, P.DESIGN_LOAD_N / 2 * 0.0315),
             "tip eject 90 N at the eject pad %.0f mm off axis (+ weight and accelerations 19 N / 0.31 N m)" % ej_arm: (109.0, 0.31 + 90.0 * ej_arm / 1000.0),
             "plunger %g N on axis (M300), pusher reaction (+19 N / 0.31 N m)" % HL.TOOLS[TOOL]["plunger_N"]: (HL.TOOLS[TOOL]["plunger_N"] + 19.0, 0.31)}
    rows = {}
    for k, (T, Mm) in cases.items():
        sep = T + 2 * Mm / R
        rows[k] = {"pull_off_N": round(T, 1), "moment_Nm": round(Mm, 3), "preload_to_just_hold_N": round(sep), "needed_with_1.5_N": round(1.5 * sep),
                   "clamp_preload_min_N": pre[0], "margin": round(pre[0] / sep, 2), "pass_1.5": pre[0] >= 1.5 * sep}
    # prong bending at the stud section: M = screw force x (b - a); two prongs (15 - 10.5) wide, 11 mm deep
    t = MCL["z1"] - MCL["z0"]
    wsum = MCL["w"] - MCL["slot_w"]
    Mb = max(f_screw) * (b - a) / 1000.0
    Z = wsum * t * t / 6.0
    sig = Mb * 1000.0 / Z
    # Hertz at the vee contacts: same formula as head_l coupling_calcs (ball on flat), largest preload + 150 N
    Es, rb = 115e3, HL.C["ball_d"] / 2
    Q = (pre[1] + P.DESIGN_LOAD_N) / (6 * math.cos(math.radians(45)))
    a_c = (3 * Q * rb / (4 * Es)) ** (1 / 3)
    p0 = 3 * Q / (2 * math.pi * a_c * a_c)
    lt = json.loads((G.LH1 / "head_l" / "out" / "report.json").read_text())["coupling"]
    return {"design": "MCL-1: an 11 mm steel fork (C45 class, ASSUMED) lying in the coupling bracket's existing latch channel, its two prongs under the stud "
                      "head, feet (heel) under the prong tips on the channel floor, and an M5 dog-point set screw through its tongue bearing on the "
                      "channel floor; tightening the screw levers the plate up about the heel and pulls the stud (retention knob) straight up, "
                      "seating the three tooling balls in the three vee seats.  The stud's cone bears on the two slot flanks, symmetric about the "
                      "stud axis: the pull is axial (no one-sided wedge, unlike the LTG-1 jaw: verification W2 does not arise)",
            "lever": {"stud_to_heel_mm": round(a, 1), "screw_to_heel_mm": round(b, 1), "ratio": round(ratio, 2)},
            "tightening": {"screw": "M5 x 12 dog-point set screw, 12.9 (bought)", "torque_Nm": MCL["torque_Nm"], "tool": "torque screwdriver 0.3-5 N m "
                           "(already on the tool list), 2.5 mm hex bit, from above", "nut_factor_K (ASSUMED band)": list(MCL["K"]),
                           "screw_force_N": [round(f) for f in f_screw]},
            "preload_band_N": pre, "latch_band_for_comparison_N": [lt["latch_preload_min_N"], lt["latch_preload_max_N"]],
            "holding": rows, "pass_all_1.5": all(r["pass_1.5"] for r in rows.values()),
            "prong_bending": {"moment_Nm": round(Mb, 2), "section_mm3": round(Z, 1), "stress_MPa": round(sig), "yield_C45_MPa (ASSUMED class)": 340,
                              "margin": round(340 / sig, 2)},
            "hertz_working_p0_GPa": round(p0 / 1000, 2), "hertz_note": "ball on flat, largest preload + 150 N; same basis as head_l (limit about 4 GPa)",
            "side_load": "nominally zero: the two flank contacts are symmetric about the stud axis and the screw and heel react on the bracket, not "
                         "the tool; the plate moves in Y only with the screw loose.  Residual side load from flank friction and plate tolerance "
                         "UNVERIFIED: commissioning check C5 re-clamps 20 times and reads the nozzle position with a dial indicator",
            "tool_change": "MANUAL at this stage: support the tool, loosen the set screw two turns, pull the fork's front tab forward %.1f mm until "
                           "its wide part stops at the bracket's front slot (the prongs are then clear of the stud head), lower the tool out; reverse to fit; re-torque; run the tip-gate "
                           "nozzle check.  The machine never changes a tool by itself in the MVP" % MCL["travel"]}


