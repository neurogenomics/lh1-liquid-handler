def scene(S, tools=DOCK_TOOLS_FULL, plan=None):
    pl = places(S)
    plan = plan or tip_plan(S)
    st, zs = station_items(S, pl)
    dr = drawer_items(S, pl)
    under = [i for i in st + dr if i["group"] == "station"]
    items = (frame_items(S, under, pl) + deck_items(S, pl) + st + shelf_items(S, pl, plan) + dock_items(S, tools) + dr
             + enclosure_items(S, floor_holes(S, pl)) + services_items(S, pl))
    return items, zs, pl, plan


def floor_holes(S, pl):
    """openings in the floor sheets (sealed with grommets / brush strip in the build): tip chute, waste drains, feet, cable glands"""
    out = []
    ch = chute(S, pl)
    out.append((ch["cx"] - 56.0, ch["cx"] + 56.0, ch["cy"] - 56.0, ch["cy"] + 56.0))
    ay = pl[find(pl, "LW")[0]]["c"][1]
    for x in CAN_X:
        out.append((x - 8.0, x + 8.0, ay - 8.0, ay + 8.0))
    steps = extension_steps(S)
    for x in (S.XR_L, S.XR_R):
        for y in feet_y_all(S):
            out.append((x - 11.0, x + 11.0, y - 21.0, y + 21.0))
    yc = y_chain(S)
    x0 = YCH["x0"] + yc["dx"]
    out.append((x0 + 10.0, x0 + 52.0, yc["fixed_y"] - 14.0, yc["fixed_y"] + 14.0))
    out.append((RAIL["x0"], RAIL["x1"], 40.0, 70.0))                 # cable gland above the control compartment (G1)
    out.append(GLANDS["G4_floor_mains_TC1_shaker"])                   # TC-1 and shaker mains leads to the back-wall outlets (G4)
    return out
