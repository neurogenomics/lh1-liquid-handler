def places(S):
    """place name -> key, centre, height, work: the layout's stations and every empty standard place (columns 1-4)"""
    from deck_rules import STATIONS
    out = {}
    for r in S.rows:
        for c in range(0, 5):
            n = f"{r}{c}"
            k = S.layout.get(n)
            if k is None and c == 0:
                continue
            k = k or "EMPTY"
            cx = TPKS["cx_abs"] if k == "TPKS" else COLX[c]         # TPK-S: the half place's own centre (comb centre)
            out[n] = dict(key=k, c=(cx, S.ry[r]), h=STATIONS[k][1], work=STATIONS[k][2], kind=STATIONS[k][0])
    return out


def find(pl, key):
    return [n for n, p in pl.items() if p["key"] == key]


def merged_pairs(pl):
    pairs = []
    for a in find(pl, "TC1"):
        b = [n for n in find(pl, "TC1LID")]
        if b:
            pairs.append((a, b[0]))
    a1, b1 = find(pl, "CTB1"), find(pl, "CTB2")
    if a1 and b1:
        pairs.append(tuple(sorted((a1[0], b1[0]), key=lambda q: int(q[1]))))
    return pairs


def window(pl, n):
    cx, cy = pl[n]["c"]
    return (cx - WIN[0], cx + WIN[0], cy - WIN[1], cy + WIN[1])


def windows(pl):
    out, used = {}, set()
    for a, b in merged_pairs(pl):
        w1, w2 = window(pl, a), window(pl, b)
        out[f"{a}+{b}"] = (min(w1[0], w2[0]), max(w1[1], w2[1]), min(w1[2], w2[2]), max(w1[3], w2[3]))
        used |= {a, b}
    for n in pl:
        if n not in used and pl[n]["key"] not in NO_WINDOW:
            out[n] = window(pl, n)
    return out


