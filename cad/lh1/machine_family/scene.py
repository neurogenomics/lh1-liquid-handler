def feet_y_all(S):
    """feet under every upright, plus one under each base-member extension joint unless an upright foot already stands within 45 mm"""
    ys = list(S.feet_y)
    for a, b in member_segments(S.FY0 + 40, S.FY1 - 40, extension_steps(S))[1:]:
        if all(abs(a - y) > 45.0 for y in ys):
            ys.append(a)
    return ys


def extension_steps(S):
    """the y positions (in this size) where an extension step put a joint: S none, M one, L two (the back ends of the earlier sizes)"""
    from geometry import ROWS
    i = ["S", "M", "L"].index(S.name)
    return [k * PITCH_Y for k in range(1, i + 1)]


def member_segments(y0, y1, steps):
    """a Y-running member of the S length extended at its back end by 110 mm per step: segments front to back"""
    n = len(steps)
    first_end = y1 - n * PITCH_Y
    segs = [(y0, first_end)]
    for k in range(n):
        segs.append((first_end + k * PITCH_Y, first_end + (k + 1) * PITCH_Y))
    return segs


