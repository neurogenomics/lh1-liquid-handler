def bar_ranges(S, y, under):
    """deck bar x ranges at y: the full deck width minus every under-deck station solid it would cross (z -46..-6, +/-6 in y)"""
    x0, x1 = S.DECK_X[0] - 10.0, S.DECK_X[1] + 3.0
    cuts = []
    for it in under:
        b = it["solid"].BoundingBox()
        if b.ymin < y + 6.0 and b.ymax > y - 6.0 and b.zmin < -6.0 and b.zmax > -46.0:
            cuts.append((b.xmin - 2.5, b.xmax + 2.5))
    cuts.sort()
    out, cur = [], x0
    for a, b in cuts:
        if a > cur:
            out.append((cur, min(a, x1)))
        cur = max(cur, b)
    if cur < x1:
        out.append((cur, x1))
    return [(a, b) for a, b in out if b - a > 15.0]


